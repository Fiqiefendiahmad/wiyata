def get_roadmap_for_role(role_slug: str) -> dict[str, Any]:
    """Build a sequenced, competency-based learning roadmap for a specific career role."""
    mappings = [m for m in CAREER_RESOURCE_MAPPINGS if m["role_slug"] == role_slug]
    stages_dict: dict[int, dict[str, Any]] = {}

    for m in mappings:
        st_num = m["stage"]
        if st_num not in stages_dict:
            stages_dict[st_num] = {
                "stage": st_num,
                "stage_name_en": m["stage_name_en"],
                "stage_name_id": m["stage_name_id"],
                "competencies": {},
            }

        c_slug = m["competency_slug"]
        if c_slug not in stages_dict[st_num]["competencies"]:
            c_meta = next((c for c in COMPETENCIES if c["slug"] == c_slug), None)
            stages_dict[st_num]["competencies"][c_slug] = {
                "competency_slug": c_slug,
                "title_en": c_meta["title_en"] if c_meta else c_slug,
                "title_id": c_meta["title_id"] if c_meta else c_slug,
                "description_en": c_meta["description_en"] if c_meta else "",
                "description_id": c_meta["description_id"] if c_meta else "",
                "expected_outcome_en": c_meta["expected_outcome_en"] if c_meta else "",
                "expected_outcome_id": c_meta["expected_outcome_id"] if c_meta else "",
                "resources": [],
            }

        stages_dict[st_num]["competencies"][c_slug]["resources"].append({
            "resource_type": m["resource_type"],
            "resource_slug": m["resource_slug"],
            "resource_title_en": m["resource_title_en"],
            "resource_title_id": m["resource_title_id"],
            "importance": m["importance"],
            "expected_proficiency": m["expected_proficiency"],
            "completion_criteria_en": m["completion_criteria_en"],
            "completion_criteria_id": m["completion_criteria_id"],
            "prerequisites": m.get("prerequisites", []),
        })

    sorted_stages = []
    for s_idx in sorted(stages_dict.keys()):
        st = stages_dict[s_idx]
        st["competencies"] = list(st["competencies"].values())
        sorted_stages.append(st)

    return {
        "role_slug": role_slug,
        "total_stages": len(sorted_stages),
        "total_resources": len(mappings),
        "stages": sorted_stages,
    }


def get_career_context_for_article(article_slug: str) -> dict[str, Any]:
    """Reverse lookup: returns which career roles and competencies rely on this Knowledge Article."""
    mappings = [m for m in CAREER_RESOURCE_MAPPINGS if m["resource_slug"] == article_slug]
    related_roles = []
    seen_roles = set()

    for m in mappings:
        r_slug = m["role_slug"]
        if r_slug not in seen_roles:
            seen_roles.add(r_slug)
            related_roles.append({
                "role_slug": r_slug,
                "stage": m["stage"],
                "importance": m["importance"],
                "expected_proficiency": m["expected_proficiency"],
                "competency_slug": m["competency_slug"],
            })

    # Gather related competencies
    comp_slugs = {m["competency_slug"] for m in mappings}
    related_comps = [c for c in COMPETENCIES if c["slug"] in comp_slugs]

    # Gather associated exercises & tools in the same competencies
    exercise_slugs = {
        m["resource_slug"]
        for m in CAREER_RESOURCE_MAPPINGS
        if m["competency_slug"] in comp_slugs and m["resource_type"] == "exercise"
    }
    tool_slugs = {
        m["resource_slug"]
        for m in CAREER_RESOURCE_MAPPINGS
        if m["competency_slug"] in comp_slugs and m["resource_type"] == "tool"
    }
    trouble_slugs = {
        m["resource_slug"]
        for m in CAREER_RESOURCE_MAPPINGS
        if m["competency_slug"] in comp_slugs and m["resource_type"] == "troubleshooting"
    }

    return {
        "article_slug": article_slug,
        "related_roles": related_roles,
        "competencies": related_comps,
        "related_exercise_slugs": list(exercise_slugs),
        "related_tool_slugs": list(tool_slugs),
        "related_troubleshooting_slugs": list(trouble_slugs),
    }


def audit_career_knowledge_graph(valid_article_slugs: list[str]) -> dict[str, Any]:
    """Verify graph integrity: detect broken references, missing roles, or orphan articles."""
    broken_references = []
    mapped_article_slugs = set()

    for m in CAREER_RESOURCE_MAPPINGS:
        if m["resource_type"] == "article":
            slug = m["resource_slug"]
            mapped_article_slugs.add(slug)
            if slug not in valid_article_slugs:
                broken_references.append({
                    "role_slug": m["role_slug"],
                    "resource_type": "article",
                    "resource_slug": slug,
                    "error": "Article slug not found in registered database",
                })

    orphan_articles = [s for s in valid_article_slugs if s not in mapped_article_slugs]

    return {
        "total_mappings": len(CAREER_RESOURCE_MAPPINGS),
        "total_competencies": len(COMPETENCIES),
        "broken_references_count": len(broken_references),
        "broken_references": broken_references,
        "orphan_articles_count": len(orphan_articles),
        "orphan_articles": orphan_articles,
        "status": "HEALTHY" if len(broken_references) == 0 else "DEGRADED",
    }
